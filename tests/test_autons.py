def a_route(project: Path, name: str, text: str) -> Path:
    path = project / "routes" / name
    path.write_text(text)
    return path


def test_each_step_is_written_as_the_route_runner_makes_its_call(tmp_path):
    project = team_project(tmp_path)
    a_route(project, "test.yaml", HEAD + STEPS)
    plan = plan_export(project)
    assert [(r.name, r.route, r.start) for r in plan.routines] == [
        ("test_route", "routes/test.yaml", (-48, -24, 0)),
    ]  # fmt: skip
    source = plan.files[0]
    assert (source.path, source.state) == (GENERATED, "new")
    assert source.after.splitlines()[3:] == [
        '#include "lemlib/api.hpp"',
        '#include "team.hpp"',  # the route's functions (and where the chassis is declared)
        '#include "custom/auton.hpp"',
        "",
        "// Test route (routes/test.yaml)",
        "void test_route() {",
        "    chassis.setPose(-48, -24, 0);",
        "    chassis.moveToPoint(24, 0, 1000);",  # LemLib's defaults: nothing to say
        # options in the order LemLib's params struct declares them, as initializers need
        "    chassis.moveToPoint(0, 0, 1200, {.forwards = false, .maxSpeed = 60, "
        ".earlyExitRange = 2}, false);",
        "    chassis.moveToPose(10, 20, 45, 2000, {.horizontalDrift = 8, .lead = 0.4});",
        "    chassis.turnToHeading(90, 800, {.direction = "
        "lemlib::AngularDirection::CCW_COUNTERCLOCKWISE, .maxSpeed = 100});",
        "    chassis.turnToPoint(0, 0, 800);",
        "    chassis.swingToHeading(180, lemlib::DriveSide::RIGHT, 900, {}, false);",
        "    chassis.swingToPoint(5, 5, lemlib::DriveSide::LEFT, 900, {.direction = "
        "lemlib::AngularDirection::CW_CLOCKWISE});",
        "    pros::delay(250);",
        "    chassis.waitUntil(6);",
        "    chassis.waitUntilDone();",
        "    startIntake();",
        "    drive(12, 1000);",
        "    drive(-5, 500, 127, false);",  # maxSpeed's default, to give async
        "    spin(3, -150, 20);",
        "    lock(lemlib::DriveSide::RIGHT);",
        "    auton::pick(auton::Speed::FAST, Mode::A);",
        "}",
    ]
    assert source.after.startswith("// Generated by vexsim from this project's routes")
    # a chassis no header declares is declared here
    team = project / "include" / "team.hpp"
    team.write_text(team.read_text().replace("extern lemlib::Chassis chassis;", ""))
    assert '#include "custom/auton.hpp"\nextern lemlib::Chassis chassis;\n\n' in (
        plan_export(project).files[0].after
    )
    assert routine_name("Left 40!") == "left_40" and routine_name("2 rings") == "route_2_rings"
    assert routine_name("Autonomous") == "autonomous_route" and routine_name("--") == "route"


def test_the_routines_are_declared_between_two_comments_in_auton_hpp(tmp_path):
    project = team_project(tmp_path)
    a_route(project, "test.yaml", HEAD + STEPS)
    a_route(project, "other.yaml", HEAD.replace("Test route", "Other") + "  - {wait: 10}\n")
    made = export(project)  # there's no auton.hpp: it's made
    header = (project / AUTON_HEADER).read_text()
    assert [(f.path, f.state) for f in made.files] == [(GENERATED, "new"), (AUTON_HEADER, "new")]
    assert header == (
        "#pragma once\n\n"
        f"{BEGIN} (vexsim writes these from routes/ when it exports the routes)\n"
        "void other();  // routes/other.yaml\n"
        "void test_route();  // routes/test.yaml\n"
        f"{END}\n"
    )
    assert "call the routines from autonomous()" in made.notes[0]
    again = export(project)
    assert not again.changes and [f.state for f in again.files] == ["unchanged", "unchanged"]
    # its own lines stay as they are; the block is put in its include guard, then kept there
    guarded = "#ifndef AUTON\n#define AUTON\n// the team's\nvoid left40();\n\n#endif  // AUTON\n"
    with_block = declarations(guarded, made.routines)
    assert with_block == (
        "#ifndef AUTON\n#define AUTON\n// the team's\nvoid left40();\n\n"
        f"{BEGIN} (vexsim writes these from routes/ when it exports the routes)\n"
        "void other();  // routes/other.yaml\n"
        "void test_route();  // routes/test.yaml\n"
        f"{END}\n\n"
        "#endif  // AUTON\n"
    )
    assert declarations(with_block, made.routines[1:]) == with_block.replace(
        "void other();  // routes/other.yaml\n", ""
    )
    assert declarations(with_block, made.routines) == with_block
    crlf = declarations("#pragma once\r\nvoid left40();\r\n", made.routines)
    assert crlf.count("\r\n") == crlf.count("\n") == 7
    with pytest.raises(ExportError, match="one of the comments"):
        declarations(f"#pragma once\n{BEGIN}\nvoid x();\n", made.routines)


def test_what_cant_be_exported_says_why(tmp_path):
    project = team_project(tmp_path)
    with pytest.raises(ExportError, match="has no routes to export"):
        plan_export(project)
    with pytest.raises(ExportError, match="isn't a PROS project"):
        plan_export(tmp_path)
    a_route(project, "test.yaml", HEAD + "  - {wait: 10}\n")
    a_route(project, "same.yaml", HEAD + "  - {wait: 20}\n")  # named Test route too
    a_route(project, "drive.yaml", HEAD.replace("Test route", "Drive") + "  - {wait: 10}\n")
    a_route(project, "broken.yaml", HEAD + "  - {wait: -5}\n")
    plan = plan_export(project)
    assert [r.name for r in plan.routines] == ["test_route"]
    assert plan.left_out == [
        "routes/broken.yaml: steps[0].wait: must be 0 or more (ms)",
        "routes/drive.yaml: the project has a drive() of its own: rename the route (Drive)",
        "routes/test.yaml: its routine would be test_route(), as routes/same.yaml's is: rename "
        "one of them",
    ]
    for path in project.glob("routes/*.yaml"):
        if path.name != "broken.yaml":
            path.unlink()
    with pytest.raises(ExportError, match="no route can be exported: routes/broken.yaml"):
        plan_export(project)


def test_the_cli_and_the_server_export_a_projects_routes(tmp_path, capsys):
    pytest.importorskip("fastapi")
    from fastapi.testclient import TestClient

    from tests.test_pages import TOKEN
    from vexsim.ui.server import create_app

    project = team_project(tmp_path)
    a_route(project, "test.yaml", HEAD + "  - {wait: 10}\n")
    assert main(["route", "export", str(project), "--dry-run"]) == 0
    out = capsys.readouterr().out
    assert "  test_route()  from routes/test.yaml, starts at (-48, -24, 0)" in out
    assert f"  {GENERATED}: new" in out and "Nothing written (--dry-run)." in out
    assert not (project / GENERATED).exists()
    app = create_app(
        tmp_path, token=TOKEN, port=8642, hosts={"testserver"}, origins={"http://testserver"}
    )
    with TestClient(app) as client:
        client.headers["authorization"] = f"Bearer {TOKEN}"
        planned = client.get("/api/routes/export", params={"project": "project"}).json()
        assert planned["project"] == "project" and planned["left_out"] == []
        assert planned["routines"] == [
            {"name": "test_route", "route": "routes/test.yaml", "start": [-48, -24, 0]}
        ]
        files = {f["path"]: f for f in planned["files"]}
        assert (
            files[GENERATED]["state"] == "new"
            and "+void test_route() {\n" in files[GENERATED]["diff"]
        )
        assert not (project / GENERATED).exists()
        done = client.post("/api/routes/export", json={"project": "project"}).json()
        assert [f["state"] for f in done["files"]] == ["new", "new"]
        again = client.get("/api/routes/export", params={"project": "project"}).json()
        assert [(f["state"], f["diff"]) for f in again["files"]] == [("unchanged", "")] * 2
        refused = client.get("/api/routes/export", params={"project": "robot.yaml"})
        assert refused.status_code == 422 and "isn't a PROS project" in refused.json()["detail"]
    assert main(["route", "export", str(project)]) == 0
    assert "Up to date: nothing to write." in capsys.readouterr().out


