def where_it_drove(spec, until_s: float) -> list[tuple[float, float, float]]:
    """Where the robot was at each millisecond of the autonomous period (s, x, y in inches),
    until ``until_s``."""
    from vexsim.app.runspec import build, check, program_factory, simulation_factory

    prepared = check(spec)
    make, mode = program_factory(prepared, build(prepared))
    sim = simulation_factory(prepared, make, mode, echo=None)()
    program = sim.program
    path: list[tuple[float, float, float]] = []

    def sample(world) -> None:
        if program.autonomous_us is not None:
            x, y = (v / 0.0254 for v in sim.robot.pose[:2])
            path.append(((world.clock.us - program.autonomous_us) / 1e6, x, y))

    sim.world.every(1, sample, name="path")
    try:
        sim.world.run_until(lambda w: bool(path) and path[-1][0] >= until_s, timeout_s=60)
    finally:
        sim.close()
    return path


def test_an_exported_route_builds_is_listed_and_runs_where_the_route_ran(
    tmp_path, lemlib_build, in_cache
):
    from vexsim.app.runspec import RunSpec

    # a copy of the project, with its robot and field where its route looks for them
    project = tmp_path / "pros_projects" / "1239e"
    shutil.copytree(PROJECT, project, ignore=shutil.ignore_patterns(".vexsim"))
    for kind in ("robots", "fields"):
        (tmp_path / kind).mkdir()
        shutil.copy(ROOT / "examples" / kind / "1239e_2026-27.yaml", tmp_path / kind)
    route = project / "routes" / "left_start.yaml"
    header = (project / AUTON_HEADER).read_text()

    done = export(project)
    assert [(f.path, f.state) for f in done.files] == [
        (GENERATED, "new"),
        (AUTON_HEADER, "changed"),
    ]
    assert (project / AUTON_HEADER).read_text().startswith(header.rstrip("\n") + "\n\n" + BEGIN)
    routine = find_routines(project).named("left_start")  # the routine list shows it
    assert (routine.start, routine.source) == ((60, 0, 90), GENERATED)
    lemlib_build(project)  # the project builds

    with in_cache():
        ran = run_route(route)
        assert ran["finished"], ran
        ends = [(s["ended_s"], s["pose"]) for s in ran["steps"]]
        spec = RunSpec(
            robot=str(tmp_path / "robots" / "1239e_2026-27.yaml"),
            program=str(project),
            field=str(tmp_path / "fields" / "1239e_2026-27.yaml"),
            routine="left_start",
            start=routine.start_pose(),
        )
        path = where_it_drove(spec, max(t for t, _ in ends) + 0.05)
    for t, pose in ends:  # each step ends where the route's did
        at = min(path, key=lambda p: abs(p[0] - t))
        assert abs(at[0] - t) < 0.001
        assert math.hypot(at[1] - pose[0], at[2] - pose[1]) < 0.25, (t, at, pose)

    text = (project / GENERATED).read_bytes()
    again = export(project)  # exporting again changes nothing
    assert not again.changes and (project / GENERATED).read_bytes() == text
