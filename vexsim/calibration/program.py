"""The calibration program (phase 14.3): a PROS 4 program of its own, for a spare slot, that
runs a calibration session's tests one at a time from a menu, each logged with vexsim's logger.

``write_program(config, plan, folder)`` writes it into a PROS project (``pros c n FOLDER``
makes one):

  src/main.cpp                          the program, the same for every robot
  include/vexsim_calibration_tests.hpp  the robot's devices and the plan's tests
  include/vexsim_log.hpp                vexsim's logger (bridge/logger.py)
  src/vexsim_log.cpp
  include/main.h                        PROS's, if the folder has none yet

It uses only the PROS 4 C API, so it builds with PROS for the robot (``pros upload --slot 8``)
and runs unchanged in vexsim (``vexsim run ROBOT.yaml --program FOLDER --mode driver``), where
calibration/student.py plays the student. The program itself (bridge/cpp/calibration/main.cpp)
says what each test does.
"""

from __future__ import annotations

import math
from pathlib import Path

from vexsim.bridge.logger import file_state, logger_files
from vexsim.calibration.plan import IMU_STILL_S, IMU_TURNS, Plan, TestPlan
from vexsim.calibration.routine import DRIVE_TESTS, MAX_MV, schedule
from vexsim.config.robot import RobotConfig
from vexsim.physics.kinematics import DriveKinematics
from vexsim.units import in_to_m

PROGRAM = Path(__file__).resolve().parent.parent / "bridge" / "cpp" / "calibration" / "main.cpp"
MAIN_H = Path(__file__).resolve().parent.parent / "bridge" / "cpp" / "calibration" / "main.h"
HEADER = "include/vexsim_calibration_tests.hpp"
MARK = "vexsim's calibration program"  # in its main.cpp: a file it may write over
PROS_TEMPLATE = "Hello PROS User!"  # in the main.cpp `pros c n` makes
RUNS = {"device_check": 1, "free_spin": 1, "imu_still": 1, "imu_turns": 2, "push": 2}
DRIVE_RUNS = 3
SPIN_DEG_S = {"slow_spin": 120.0}  # a spin in place's speed; the distance sweeps' otherwise
SWEEP_DEG_S = 60.0
FREE_SPIN_MV = (3000, 6000, 9000, 12000)
DEVICE_TYPES = {"motor": 2, "rotation": 4, "imu": 6, "distance": 7, "gps": 20}
NO_SPOT = '{0.0, 0.0, 0.0, {"", "", ""}}'  # where a test that isn't there would start


class ProgramError(Exception):
    """The folder isn't one to write the program into (it holds other code)."""


def _c(text: str) -> str:
    """A C string literal (ASCII: the brain's font has nothing else)."""
    out = []
    for ch in text:
        if ch in '\\"':
            out.append("\\" + ch)
        elif " " <= ch <= "~":
            out.append(ch)
        else:
            out.append("?")
    return '"' + "".join(out) + '"'


def _num(value: float) -> str:
    text = f"{value:.6g}"
    return text if any(c in text for c in ".e") else text + ".0"


def _direction(degrees: float) -> str:
    """Which way a heading (deg, counter-clockwise from the robot's front) points, in words."""
    names = [
        "front",
        "front left",
        "left",
        "back left",
        "back",
        "back right",
        "right",
        "front right",
    ]
    return names[round((degrees % 360) / 45) % 8]


def _where(config: RobotConfig, sensor) -> str:
    """Where a sensor is on the robot, and which way it faces: to find it with a hand."""
    x0, y0, x1, y1 = config.body.outline.bounds
    x, y = sensor.pos_in
    along = "front" if x > x1 / 3 else "back" if x < x0 / 3 else "middle"
    side = "left" if y > y1 / 3 else "right" if y < y0 / 3 else "center"
    place = along if side == "center" else side if along == "middle" else f"{along} {side}"
    facing = _direction(sensor.heading_deg)
    return f"{place}, facing {dict(front='forward', back='backward').get(facing, facing)}"


def drive_motors(config: RobotConfig) -> list[tuple[int, int, int, str]]:
    """The drive's motors in the program's order: (raw port, direction, group index, group)."""
    out = []
    for g, (name, gear) in enumerate(config.drivetrain.gearing.items()):
        out += [(abs(p), 1 if p > 0 else -1, g, name) for p in gear.motors]
    return out


def header_text(config: RobotConfig, plan: Plan) -> str:
    """include/vexsim_calibration_tests.hpp: the robot's devices and the plan's tests."""
    kin = DriveKinematics.from_config(config)
    motors = drive_motors(config)
    gearing = list(config.drivetrain.gearing.values())
    rows = {name: kin.matrix[k] for k, name in enumerate(kin.groups)}
    lines = [
        f"// Generated by `vexsim calibration program` for {_c(config.name or 'robot')[1:-1]} on",
        f"// {_c(plan.field)[1:-1]}: the robot's devices and the plan's tests, for the calibration",
        "// program (src/main.cpp). Write it again when the robot config, the field or the plan",
        "// changes.",
        "#pragma once",
        "",
        "namespace cal {",
        "",
        f"constexpr const char* ROBOT = {_c(config.name or 'robot')};",
        f"constexpr const char* FIELD = {_c(plan.field)};",
        "",
        "// The drive's motors: raw port, the config's direction (-1: reversed), its group, its",
        "// cartridge's rpm, the wheels' inches per motor turn, and the inches the robot goes",
        "// forward per motor degree (0: it doesn't drive forward).",
        "struct Motor {",
        "\tint port;",
        "\tint direction;",
        "\tint group;",
        "\tint rpm;",
        "\tdouble in_per_rev;",
        "\tdouble in_per_deg;",
        "};",
        f"constexpr int MOTOR_COUNT = {len(motors)};",
        "constexpr Motor MOTORS[MOTOR_COUNT] = {",
    ]
    for port, direction, g, name in motors:
        gear = gearing[g]
        wheel = config.drivetrain.wheel(gear.wheels[0])
        per_rev = math.pi * wheel.diameter_in * gear.speed_ratio
        forward = math.degrees(abs(rows[name][0])) * in_to_m(1.0)  # motor degrees per inch
        per_deg = 1 / forward if forward > 1e-6 else 0.0
        rpm = round(gear.motor_free_rpm)
        lines.append(
            f"\t{{{port}, {direction}, {g}, {rpm}, {_num(per_rev)}, {_num(per_deg)}}},  // {name}"
        )
    lines += [
        "};",
        "",
        "// Each group of drive motors, and which way its wheels roll driving it forward.",
        "struct Group {",
        "\tconst char* name;",
        "\tconst char* toward;",
        "};",
        f"constexpr int GROUP_COUNT = {len(gearing)};",
        "constexpr Group GROUPS[GROUP_COUNT] = {",
    ]
    for name, gear in config.drivetrain.gearing.items():
        heading = config.drivetrain.wheel(gear.wheels[0]).heading_deg
        lines.append(f"\t{{{_c(name)}, {_c(_direction(heading))}}},")
    mix = [kin.fractions(*axis) for axis in ((1, 0, 0), (0, 1, 0), (0, 0, 1))]
    lines += [
        "};",
        "",
        "// Each motor's voltage (raw mV) to drive forward, left and turn counter-clockwise, each",
        "// at full speed: Drive mode and the spins in place mix them.",
        "constexpr int MIX[MOTOR_COUNT][3] = {",
    ]
    for port, direction, _, name in motors:
        mv = [round(direction * f.get(name, 0.0) * MAX_MV) for f in mix]
        lines.append(f"\t{{{mv[0]}, {mv[1]}, {mv[2]}}},  // {port}")
    turn_per_deg = max(abs(rows[name][2]) for name in kin.groups)
    top_yaw = math.degrees(kin.top_speeds()[2])
    lines += [
        "};",
        "// Drive motor degrees per degree the robot turns in place, and the turning (of MIX) per",
        "// degree a second: where a spin in place starts.",
        f"constexpr double MOTOR_DEG_PER_TURN_DEG = {_num(turn_per_deg)};",
        f"constexpr double TURN_PER_DEG_S = {_num(1 / top_yaw if top_yaw else 0.0)};",
        "",
    ]
    lines += _devices(config)
    lines += _tests(config, plan, motors)
    lines += ["", "}  // namespace cal", ""]
    return "\n".join(lines)


def _devices(config: RobotConfig) -> list[str]:
    devices = []
    for port, _, _, name in drive_motors(config):
        devices.append((port, DEVICE_TYPES["motor"], f"{name} drive motor"))
    what = {"imu": "IMU", "distance": "distance sensor", "gps": "GPS sensor"}
    for sensor in sorted(config.sensors, key=lambda s: s.port):
        if sensor.type == "rotation":
            kind = "tracking wheel" if sensor.tracking_wheel else "rotation sensor"
        else:
            kind = what[sensor.type]
        devices.append((sensor.port, DEVICE_TYPES[sensor.type], kind))
    imu = next((s.port for s in config.sensors if s.type == "imu"), 0)
    lines = [
        "// Every device the tests use: its port, its type (pros::c::v5_device_e_t), what it is.",
        "struct Device {",
        "\tint port;",
        "\tint type;",
        "\tconst char* what;",
        "};",
        f"constexpr int DEVICE_COUNT = {len(devices)};",
        "constexpr Device DEVICES[DEVICE_COUNT] = {",
        *(f"\t{{{p}, {t}, {_c(w)}}}," for p, t, w in devices),
        "};",
        f"constexpr int IMU_PORT = {imu};  // 0: none",
        "",
        "// Tracking wheels: which way each counts (raw) with the robot pushed forward, and pushed",
        "// left: 1, -1, or 0 for hardly.",
        "struct Tracking {",
        "\tint port;",
        "\tint forward;",
        "\tint left;",
        "};",
    ]
    tracking = []
    for sensor in config.sensors:
        if sensor.type == "rotation" and sensor.tracking_wheel:
            h = math.radians(sensor.tracking_wheel.heading_deg)
            sign = -1 if sensor.reversed else 1

            def way(component: float, sign: int = sign) -> int:
                return 0 if abs(component) < 0.5 else sign * (1 if component > 0 else -1)

            tracking.append(f"\t{{{sensor.port}, {way(math.cos(h))}, {way(math.sin(h))}}},")
    lines += [
        f"constexpr int TRACKING_COUNT = {len(tracking)};",
        "constexpr Tracking TRACKING[TRACKING_COUNT + 1] = {",
        *tracking,
        "\t{0, 0, 0},",
        "};",
        "",
        "// Distance sensors, and where each is on the robot: a hand covers each in turn.",
        "struct Distance {",
        "\tint port;",
        "\tconst char* where;",
        "};",
    ]
    distances = [
        f"\t{{{s.port}, {_c(_where(config, s))}}},"
        for s in sorted(config.sensors, key=lambda s: s.port)
        if s.type == "distance"
    ]
    lines += [
        f"constexpr int DISTANCE_COUNT = {len(distances)};",
        "constexpr Distance DISTANCES[DISTANCE_COUNT + 1] = {",
        *distances,
        '\t{0, ""},',
        "};",
        "",
    ]
    return lines


def _spot(test: TestPlan) -> str:
    x, y, h = test.spot.pose
    short = [*test.spot.short, "", "", ""][:3]
    return f"{{{_num(x)}, {_num(y)}, {_num(h)}, {{{', '.join(_c(t) for t in short)}}}}}"


def _tests(config: RobotConfig, plan: Plan, motors: list) -> list[str]:
    session = plan.session()
    lines = [
        "// An open-loop step: how long, how the motors stop (0 coast, 1 brake), each motor's",
        "// raw voltage (mV; 0: stopped).",
        "struct Step {",
        "\tconst char* name;",
        "\tint ms;",
        "\tint brake;",
        "\tint mv[MOTOR_COUNT];",
        "};",
        "",
        "// Where a test starts: the pose (field inches; degrees counter-clockwise from +x), and",
        "// how to put the robot there.",
        "struct Spot {",
        "\tdouble x;",
        "\tdouble y;",
        "\tdouble heading;",
        "\tconst char* place[3];",
        "};",
        "",
        "// The driving tests: their steps (slowed and shortened to `scale` where the field has",
        "// less room), and their envelope: no drive motor turns further, nor the robot (IMU).",
        "struct DriveTest {",
        "\tconst char* key;",
        "\tconst char* title;",
        "\tdouble scale;",
        "\tint step_count;",
        "\tconst Step* steps;",
        "\tdouble max_motor_deg;",
        "\tdouble max_turn_deg;  // 0: no IMU",
        "\tSpot spot;",
        "};",
    ]
    drive = [t for t in plan.drive if t.spot is not None]
    for test in drive:
        lines.append(f"constexpr Step STEPS_{test.key.upper()}[] = {{")
        plan_steps = schedule(config, test.steps)
        for (start, step, millivolts), (end, _, _) in zip(plan_steps, plan_steps[1:], strict=False):
            mv = ", ".join(str(millivolts.get(port, 0)) for port, _, _, _ in motors)
            brake = 1 if step.brake == "brake" else 0
            lines.append(f"\t{{{_c(step.name)}, {end - start}, {brake}, {{{mv}}}}},")
        lines.append("};")
    lines += [
        f"constexpr int DRIVE_TEST_COUNT = {len(drive)};",
        "constexpr DriveTest DRIVE_TESTS[DRIVE_TEST_COUNT + 1] = {",
    ]
    for test in drive:
        steps = f"STEPS_{test.key.upper()}"
        lines.append(
            f"\t{{{_c(test.key)}, {_c(DRIVE_TESTS[test.key])}, {_num(test.scale)}, "
            f"sizeof {steps} / sizeof {steps}[0], {steps}, {_num(round(test.max_motor_deg))}, "
            f"{_num(round(test.max_turn_deg or 0))}, {_spot(test)}}},"
        )
    lines += [f'\t{{"", "", 1.0, 0, nullptr, 0.0, 0.0, {NO_SPOT}}},', "};", ""]
    push = plan.push if plan.push is not None and plan.push.spot is not None else None
    lines += [
        "// The push lane: how long, and its start.",
        f"constexpr double PUSH_IN = {_num(push.length_in if push else 0.0)};",
        f"constexpr Spot PUSH_SPOT = {_spot(push) if push else NO_SPOT};",
        "",
        "// Spins in place, by the IMU: how many turns, how fast (deg/s), where.",
        "struct Spin {",
        "\tconst char* key;",
        "\tconst char* title;",
        "\tdouble turns;",
        "\tdouble deg_per_s;",
        "\tSpot spot;",
        "};",
    ]
    spins = [t for t in [plan.slow_spin, *plan.sweeps] if t is not None and t.spot is not None]
    lines += [
        f"constexpr int SPIN_COUNT = {len(spins)};",
        "constexpr Spin SPINS[SPIN_COUNT + 1] = {",
    ]
    for test in spins:
        speed = SPIN_DEG_S.get(test.key, SWEEP_DEG_S)
        title = test.title.split(",")[0]
        lines.append(
            f"\t{{{_c(test.key)}, {_c(title)}, {_num(test.turns)}, {_num(speed)}, {_spot(test)}}},"
        )
    lines += [
        f'\t{{"", "", 0.0, 0.0, {NO_SPOT}}},',
        "};",
        "",
        "constexpr int FREE_SPIN_MV[] = {" + ", ".join(map(str, FREE_SPIN_MV)) + "};",
        f"constexpr int IMU_STILL_S = {IMU_STILL_S};",
        f"constexpr int IMU_TURNS = {IMU_TURNS};",
        "",
        "// The menu: the session's tests in order (each test's number, on its map too), and the",
        "// runs each takes.",
        "struct MenuItem {",
        "\tconst char* key;",
        "\tconst char* title;",
        "\tint runs;",
        "};",
        f"constexpr int MENU_COUNT = {len(session)};",
        "constexpr MenuItem MENU[MENU_COUNT] = {",
    ]
    for key, title, _ in session:
        runs = RUNS.get(key, DRIVE_RUNS if key in DRIVE_TESTS else 1)
        lines.append(f"\t{{{_c(key)}, {_c(title)}, {runs}}},")
    lines.append("};")
    return lines


def program_files(config: RobotConfig, plan: Plan, project: str | Path) -> list[tuple[Path, str]]:
    """The program's files for a project folder, and what each holds."""
    project = Path(project)
    out = [
        (project / "src" / "main.cpp", PROGRAM.read_text(encoding="utf-8")),
        (project / HEADER, header_text(config, plan)),
        *logger_files(project),
    ]
    if not (project / "include" / "main.h").is_file():
        out.append((project / "include" / "main.h", MAIN_H.read_text(encoding="utf-8")))
    return out


def check_folder(project: str | Path, *, force: bool = False) -> None:
    """Raises ProgramError unless the folder is free for the program: empty, a new PROS
    project, or the program's own (``force``: a main.cpp of someone else's is written over)."""
    project = Path(project)
    ours = {"main.cpp", "vexsim_log.cpp"}
    src = project / "src"
    others = sorted(
        str(p.relative_to(project))
        for p in (src.rglob("*") if src.is_dir() else [])
        if p.suffix in (".c", ".cc", ".cpp") and p.name not in ours
    )
    if others:
        raise ProgramError(
            f"{project} has code of its own ({', '.join(others[:3])}): the calibration program "
            "goes in a project of its own (pros c n vexsim_calibration)"
        )
    main = src / "main.cpp"
    if main.is_file() and not force:
        text = main.read_text(encoding="utf-8", errors="replace")
        if MARK not in text and PROS_TEMPLATE not in text:
            raise ProgramError(
                f"{main} isn't the calibration program's, nor a new PROS project's: the "
                "program goes in a project of its own (pros c n vexsim_calibration), or "
                "--force writes over it"
            )


def write_program(
    config: RobotConfig, plan: Plan, project: str | Path, *, force: bool = False
) -> list[tuple[Path, str]]:
    """Write the program into a project folder (check_folder says which); each file, and
    whether it was "new", "updated" or already the "same"."""
    check_folder(project, force=force)
    out = []
    for path, text in program_files(config, plan, project):
        state = file_state(path, text)
        if state != "same":
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
        out.append((path, "updated" if state == "different" else state))
    return out
