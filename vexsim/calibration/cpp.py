"""C++ for the real robot: the calibration routine and a logger, generated for one robot config.

``write_routine(config, project)`` adds two files to a PROS 4 project:

  include/vexsim_calibration.hpp   run(), start_logging(), save()
  src/vexsim_calibration.cpp       the robot's ports, the routine's voltages, the logger

They only use the PROS 4 C API, so they build with the real PROS toolchain and,
unchanged, in vexsim (``vexsim run ROBOT.yaml --program PROJECT``). The log is
saved to the SD card as /usd/vexsim_log.csv, or printed to the terminal between
``#vexsim-log begin`` and ``#vexsim-log end`` lines when there is no card.
"""

from __future__ import annotations

from pathlib import Path
from string import Template

from vexsim.calibration.log import columns_for
from vexsim.calibration.routine import Step, schedule, standard_routine
from vexsim.config.robot import RobotConfig

HEADER = Template("""\
// Generated by `vexsim calibration-routine` for "$name". Regenerate it if the robot changes.
#pragma once

namespace vexsim_calibration {

// Calibrates the IMU, drives the calibration routine ($seconds s; it needs about 3 x 3 m of
// open floor: start in the middle, facing the longer free direction), stops, and saves the log.
// Call it from autonomous(), or from opcontrol() on a button press.
void run();

// Logs every 10 ms in the background, for your own programs, until save(). Motor commands
// aren't known then, so vexsim replays the motors' measured voltages.
void start_logging();

// Writes the log to /usd/vexsim_log.csv, or prints it to the terminal if there is no SD card.
// Returns the number of rows.
int save();

}  // namespace vexsim_calibration
""")

SOURCE = Template("""\
// Generated by `vexsim calibration-routine` for "$name". Regenerate it if the robot changes.
// Logs what the robot measures every 10 ms, in vexsim's robot-log format.
#include "vexsim_calibration.hpp"

#include <cmath>
#include <cstdint>
#include <cstdio>
#include <string>
#include <vector>

#include "api.h"

namespace vexsim_calibration {
namespace {

constexpr int MOTOR_COUNT = $motor_count;
constexpr int MOTORS[MOTOR_COUNT] = {$motors};  // raw (positive) ports

struct Step {
\tconst char* name;
\tint ms;
\tint brake;  // 0 coast, 1 brake: how the motors stop when the step is still
\tint mv[MOTOR_COUNT];  // raw voltage per motor (0 = stop)
};

const Step STEPS[] = {
$steps
};

const char* const HEADER = "$header";

std::vector<std::string> g_rows;
bool g_commands_known = false;
int g_cmd_mv[22] = {};
int g_brake[22] = {};
pros::Task* g_task = nullptr;
bool g_logging = false;

void add(std::string& row, const char* format, double value, bool valid = true) {
\trow += ',';
\tif (!valid || !std::isfinite(value)) return;
\tchar buf[32];
\tstd::snprintf(buf, sizeof buf, format, value);
\trow += buf;
}

void motor(std::string& row, int port) {
\tint32_t mv = pros::c::motor_get_voltage(port);
\tadd(row, "%.0f", g_cmd_mv[port], g_commands_known);
\trow += ',';  // m<p>_cmd_rpm: the routine only uses voltages
\tadd(row, "%.0f", g_commands_known ? g_brake[port] : pros::c::motor_get_brake_mode(port));
\tadd(row, "%.2f", pros::c::motor_get_position(port));
\tadd(row, "%.2f", pros::c::motor_get_actual_velocity(port));
\tint32_t ma = pros::c::motor_get_current_draw(port);
\tadd(row, "%.0f", ma, ma != PROS_ERR);
\tadd(row, "%.0f", mv, mv != PROS_ERR);
\tadd(row, "%.1f", pros::c::motor_get_temperature(port));
}

void rotation(std::string& row, int port) {
\tint32_t cdeg = pros::c::rotation_get_position(port);
\tadd(row, "%.0f", cdeg, cdeg != PROS_ERR);
}

void imu(std::string& row, int port) { add(row, "%.4f", pros::c::imu_get_rotation(port)); }

void distance(std::string& row, int port) {
\tint32_t mm = pros::c::distance_get(port);
\tadd(row, "%.0f", mm, mm != PROS_ERR && mm != 9999);
}

void gps(std::string& row, int port) {
\tpros::Gps sensor(port);
\tpros::gps_position_s_t p = sensor.get_position();
\tadd(row, "%.4f", p.x);
\tadd(row, "%.4f", p.y);
\tadd(row, "%.3f", sensor.get_heading());
\tadd(row, "%.4f", sensor.get_error());
}

void sample(std::uint32_t elapsed_ms) {
\tstd::string row = std::to_string(elapsed_ms);
\tint32_t battery_mv = pros::c::battery_get_voltage();
\tint32_t battery_ma = pros::c::battery_get_current();
\tadd(row, "%.0f", battery_mv, battery_mv != PROS_ERR);
\tadd(row, "%.0f", battery_ma, battery_ma != PROS_ERR);
$sample
\tg_rows.push_back(row);
}

void apply(const Step& step) {
\tfor (int i = 0; i < MOTOR_COUNT; i++) {
\t\tint port = MOTORS[i];
\t\tauto brake = step.brake ? pros::E_MOTOR_BRAKE_BRAKE : pros::E_MOTOR_BRAKE_COAST;
\t\tpros::c::motor_set_brake_mode(port, brake);
\t\tif (step.mv[i] != 0) {
\t\t\tpros::c::motor_move_voltage(port, step.mv[i]);
\t\t} else {
\t\t\tpros::c::motor_brake(port);  // stops with the brake mode
\t\t}
\t\tg_cmd_mv[port] = step.mv[i];
\t\tg_brake[port] = step.brake;
\t}
}

}  // namespace

void run() {
\tg_logging = false;
\tfor (int port : MOTORS) {
\t\tpros::c::motor_set_encoder_units(port, pros::E_MOTOR_ENCODER_DEGREES);
\t\tpros::c::motor_set_brake_mode(port, pros::E_MOTOR_BRAKE_COAST);
\t\tpros::c::motor_brake(port);
\t}
$setup
\tg_rows.clear();
\tg_rows.reserve($rows);
\tg_commands_known = true;
\tstd::uint32_t start = pros::millis(), now = start;
\tfor (const Step& step : STEPS) {
\t\tapply(step);
\t\tfor (int t = 0; t < step.ms; t += 10) {
\t\t\tsample(now - start);
\t\t\tpros::c::task_delay_until(&now, 10);
\t\t}
\t}
\tfor (int port : MOTORS) {
\t\tpros::c::motor_set_brake_mode(port, pros::E_MOTOR_BRAKE_BRAKE);
\t\tpros::c::motor_brake(port);
\t}
\tg_commands_known = false;
\tsave();
}

void start_logging() {
\tif (g_logging) return;
\tg_rows.clear();
\tg_commands_known = false;
\tg_logging = true;
\tif (g_task == nullptr) {
\t\tg_task = new pros::Task([] {
\t\t\tstd::uint32_t start = pros::millis(), now = start;
\t\t\twhile (true) {
\t\t\t\tif (g_logging) sample(now - start);
\t\t\t\tpros::c::task_delay_until(&now, 10);
\t\t\t}
\t\t});
\t}
}

int save() {
\tg_logging = false;
\tint rows = static_cast<int>(g_rows.size());
\tFILE* file = pros::c::usd_is_installed() ? std::fopen("/usd/vexsim_log.csv", "w") : nullptr;
\tif (file != nullptr) {
\t\tstd::fprintf(file, "%s\\n", HEADER);
\t\tfor (const std::string& row : g_rows) std::fprintf(file, "%s\\n", row.c_str());
\t\tstd::fclose(file);
\t\tstd::printf("vexsim: wrote %d log rows to /usd/vexsim_log.csv\\n", rows);
\t\treturn rows;
\t}
\tstd::printf("#vexsim-log begin\\n%s\\n", HEADER);
\tfor (int i = 0; i < rows; i++) {
\t\tstd::printf("%s\\n", g_rows[i].c_str());
\t\tif (i % 20 == 19) {  // let the terminal keep up
\t\t\tstd::fflush(stdout);
\t\t\tpros::delay(2);
\t\t}
\t}
\tstd::printf("#vexsim-log end\\n");
\tstd::fflush(stdout);
\treturn rows;
}

}  // namespace vexsim_calibration
""")


def generate(config: RobotConfig, steps: list[Step] | None = None) -> tuple[str, str]:
    """(header, source) for a robot config."""
    steps = standard_routine(config) if steps is None else steps
    plan = schedule(config, steps)
    motors = sorted({abs(p) for g in config.drivetrain.gearing.values() for p in g.motors})
    step_lines = []
    for (start, step, millivolts), (end, _, _) in zip(plan, plan[1:], strict=False):
        mv = ", ".join(str(millivolts[p]) for p in motors)
        brake = 1 if step.brake == "brake" else 0
        step_lines.append(f'\t{{"{step.name}", {end - start}, {brake}, {{{mv}}}}},')
    sample, setup = [], []
    for p in motors:
        sample.append(f"\tmotor(row, {p});")
    for sensor in sorted(config.sensors, key=lambda s: s.port):
        p = sensor.port
        if sensor.type == "rotation":
            sample.append(f"\trotation(row, {p});")
            setup.append(f"\tpros::c::rotation_set_reversed({p}, false);  // log raw readings")
        elif sensor.type == "imu":
            sample.append(f"\timu(row, {p});")
            setup.append(f"\tpros::c::imu_reset_blocking({p});  // keep the robot still")
        elif sensor.type == "distance":
            sample.append(f"\tdistance(row, {p});")
        elif sensor.type == "gps":
            sample.append(f"\tgps(row, {p});")
    seconds = plan[-1][0] / 1000
    name = (config.name or "robot").replace('"', "'")
    values = {
        "name": name,
        "seconds": f"{seconds:g}",
        "motor_count": len(motors),
        "motors": ", ".join(map(str, motors)),
        "steps": "\n".join(step_lines),
        "header": ",".join(columns_for(config)),
        "sample": "\n".join(sample),
        "setup": "\n".join(setup),
        "rows": plan[-1][0] // 10 + 10,
    }
    return HEADER.substitute(values), SOURCE.substitute(values)


def write_routine(config: RobotConfig, project: str | Path) -> list[Path]:
    """Add the routine to a PROS project folder; returns the files written."""
    project = Path(project)
    header, source = generate(config)
    paths = [
        project / "include" / "vexsim_calibration.hpp",
        project / "src" / "vexsim_calibration.cpp",
    ]
    for path, text in zip(paths, (header, source), strict=True):
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
    return paths
